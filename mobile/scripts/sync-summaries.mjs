// Brings the website's study material into the app: the authored lesson HTML +
// questions, the reading-path logic (pathMeta.js) and the stylesheet the lessons
// are written against. The website is the source of truth: fix a lesson there,
// then run `npm run sync:summaries` here and commit the result.
//
//   node scripts/sync-summaries.mjs          copy (overwrite)
//   node scripts/sync-summaries.mjs --check  exit 1 if the app has drifted
//
// Only import paths are rewritten (the website's relative paths -> the app's
// alias); the content itself is copied byte for byte.
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const site = resolve(here, '../../my-react-app/src');
const summaries = join(site, 'components/summaries');
const out = resolve(here, '../src/features/summaries');
const check = process.argv.includes('--check');

const banner = (from) =>
  `// AUTO-COPIED from my-react-app/src/${from}. Do not edit here:\n` +
  `// change the website's file, then run \`npm run sync:summaries\` in mobile/.\n`;

const files = [];

for (const name of readdirSync(join(summaries, 'content')).filter((f) => f.endsWith('.js'))) {
  let src = readFileSync(join(summaries, 'content', name), 'utf8').replace(/\r\n/g, '\n');
  src = src.replace(/from '\.\.\/\.\.\/\.\.\/utils\/tracks\.js'/g, "from '@/lib/tracks'");
  files.push({ target: join(out, 'content', name), from: `components/summaries/content/${name}`, body: src });
}

let pathMeta = readFileSync(join(summaries, 'pathMeta.js'), 'utf8').replace(/\r\n/g, '\n');
pathMeta = pathMeta.replace(/from '\.\.\/\.\.\/utils\/tracks\.js'/g, "from '@/lib/tracks'");
files.push({ target: join(out, 'pathMeta.js'), from: 'components/summaries/pathMeta.js', body: pathMeta });

// The lessons are styled by the website's Summaries.css plus the :root design
// tokens it reads. Both go into one string the lesson WebView injects.
const rootBlock = /^:root \{[\s\S]*?^\}/m.exec(readFileSync(join(site, 'index.css'), 'utf8').replace(/\r\n/g, '\n'));
if (!rootBlock) throw new Error('could not find :root in index.css');
const css = readFileSync(join(summaries, 'Summaries.css'), 'utf8').replace(/\r\n/g, '\n');
const cssModule =
  `// AUTO-GENERATED by scripts/sync-summaries.mjs from my-react-app/src/index.css (:root)\n` +
  `// and components/summaries/Summaries.css. Do not edit here.\n` +
  `export const SUMMARY_CSS = ${JSON.stringify(`${rootBlock[0]}\n${css}`)};\n`;
files.push({ target: join(out, 'styles.generated.ts'), from: 'Summaries.css', body: cssModule, raw: true });

let drift = 0;
for (const f of files) {
  const body = f.raw ? f.body : banner(f.from) + f.body;
  if (check) {
    const current = existsSync(f.target) ? readFileSync(f.target, 'utf8') : '';
    if (current !== body) {
      drift += 1;
      console.log(`drifted: ${f.target.replace(out, 'summaries')}`);
    }
  } else {
    mkdirSync(dirname(f.target), { recursive: true });
    writeFileSync(f.target, body);
  }
}

if (check) {
  if (drift) {
    console.log(`${drift} file(s) differ from the website. Run: npm run sync:summaries`);
    process.exit(1);
  }
  console.log('summaries are in sync with the website');
} else {
  console.log(`wrote ${files.length} files to src/features/summaries`);
}
